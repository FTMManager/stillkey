//! `font`: turns `assets/spleen-8x16.bdf` into `lib/sk-kcore/src/font.rs`
//! (docs/10 section 5.3). Only the glyphs of the bytes 0x20-0x7E are taken.

use std::fs;
use std::path::PathBuf;

use crate::util::workspace_root;

const FIRST: u32 = 0x20;
const LAST: u32 = 0x7E;
const COUNT: usize = (LAST - FIRST + 1) as usize;
const ROWS: usize = 16;

pub type Glyph = [u8; ROWS];

/// The glyphs 0x20-0x7E of a BDF font whose cells are 8 by 16 pixels.
pub fn parse_bdf(text: &str) -> Result<Vec<Glyph>, String> {
    let mut glyphs: Vec<Option<Glyph>> = vec![None; COUNT];
    // The glyph being read: its code, and its rows once `BITMAP` was seen.
    let mut code: Option<u32> = None;
    let mut rows: Option<Vec<u8>> = None;
    for (number, line) in text.lines().enumerate() {
        let line = line.trim();
        let wanted = code.is_some_and(|c| (FIRST..=LAST).contains(&c));
        let fail = |what: &str| format!("line {}: {what}: {line}", number + 1);
        if let Some(value) = line.strip_prefix("ENCODING ") {
            code = Some(value.trim().parse().map_err(|_| fail("not a character code"))?);
            rows = None;
        } else if let Some(bbx) = line.strip_prefix("BBX ") {
            if wanted && !bbx.starts_with("8 16 ") {
                return Err(fail("the cell is not 8 by 16 pixels"));
            }
        } else if line == "BITMAP" {
            rows = Some(Vec::new());
        } else if line == "ENDCHAR" {
            if let (true, Some(c), Some(found)) = (wanted, code, rows.take()) {
                let glyph: Glyph = found.try_into().map_err(|_| fail("the glyph does not have 16 rows"))?;
                glyphs[(c - FIRST) as usize] = Some(glyph);
            }
            code = None;
        } else if let Some(found) = &mut rows {
            if wanted {
                if line.len() != 2 {
                    return Err(fail("a row is not two hexadecimal digits"));
                }
                found.push(u8::from_str_radix(line, 16).map_err(|_| fail("a row is not two hexadecimal digits"))?);
            }
        }
    }
    glyphs
        .into_iter()
        .enumerate()
        .map(|(i, glyph)| glyph.ok_or_else(|| format!("no glyph for byte {:#04x}", FIRST as usize + i)))
        .collect()
}

/// The source text of `lib/sk-kcore/src/font.rs`.
pub fn render(glyphs: &[Glyph]) -> String {
    let mut out = String::from(
        "//! Spleen 8x16 2.2.0, the glyphs of the bytes 0x20-0x7E. Generated by\n\
         //! `cargo xtask font` from `assets/spleen-8x16.bdf`: do not edit.\n\
         //!\n\
         //! Spleen is Copyright (c) 2018-2026, Frederic Cambus, under the BSD\n\
         //! 2-Clause license: `assets/spleen-LICENSE`.\n\
         \n\
         /// Sixteen rows per glyph, the top row first; bit 7 of a row is its left pixel.\n",
    );
    out.push_str(&format!("pub const GLYPHS: [[u8; {ROWS}]; {}] = [\n", glyphs.len()));
    for (i, glyph) in glyphs.iter().enumerate() {
        let rows: Vec<String> = glyph.iter().map(|row| format!("{row:#04x}")).collect();
        out.push_str(&format!("    [{}], // {:#04x}\n", rows.join(", "), FIRST as usize + i));
    }
    out.push_str(
        "];\n\
         \n\
         /// The glyph of a byte; that of `?` for a byte outside 0x20-0x7E.\n\
         pub const fn glyph(byte: u8) -> &'static [u8; 16] {\n    \
             match byte {\n        \
                 0x20..=0x7E => &GLYPHS[(byte - 0x20) as usize],\n        \
                 _ => &GLYPHS[(b'?' - 0x20) as usize],\n    \
             }\n\
         }\n",
    );
    out
}

fn source() -> PathBuf {
    workspace_root().join("assets").join("spleen-8x16.bdf")
}

fn generated() -> PathBuf {
    workspace_root().join("lib").join("sk-kcore").join("src").join("font.rs")
}

/// What `font.rs` must hold, from the font file as it is now.
fn expected() -> Result<String, String> {
    let path = source();
    let text = fs::read_to_string(&path)
        .map_err(|e| format!("{}: {e} (tools/fetch-font.sh downloads it)", path.display()))?;
    Ok(render(&parse_bdf(&text)?))
}

pub fn generate() -> Result<(), String> {
    let path = generated();
    fs::write(&path, expected()?).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("{}", path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn glyph_text(code: u32, bbx: &str, rows: &[&str]) -> String {
        format!("STARTCHAR c\nENCODING {code}\nSWIDTH 500 0\nDWIDTH 8 0\nBBX {bbx}\nBITMAP\n{}\nENDCHAR\n", rows.join("\n"))
    }

    /// A font in which every row of glyph `c` is the byte `c`.
    fn font() -> String {
        let mut text = String::from("STARTFONT 2.1\nFONTBOUNDINGBOX 8 16 0 -4\nCHARS 97\n");
        for code in 0x1F..=0x7F {
            let row = format!("{code:02X}");
            text.push_str(&glyph_text(code, "8 16 0 -4", &[row.as_str(); 16]));
        }
        text + "ENDFONT\n"
    }

    #[test]
    fn takes_the_95_glyphs_in_byte_order() {
        let glyphs = parse_bdf(&font()).unwrap();
        assert_eq!(glyphs.len(), 95);
        assert_eq!(glyphs[0], [0x20; 16]);
        assert_eq!(glyphs[94], [0x7E; 16]);
    }

    #[test]
    fn keeps_the_rows_in_order() {
        let rows: Vec<String> = (0..16).map(|i| format!("{:02X}", i * 3)).collect();
        let rows: Vec<&str> = rows.iter().map(String::as_str).collect();
        let text = font().replace(&glyph_text(0x41, "8 16 0 -4", &["41"; 16]), &glyph_text(0x41, "8 16 0 -4", &rows));
        let glyphs = parse_bdf(&text).unwrap();
        assert_eq!(glyphs[0x41 - 0x20], core::array::from_fn(|i| i as u8 * 3));
    }

    #[test]
    fn a_missing_glyph_is_named() {
        let text = font().replace(&glyph_text(0x41, "8 16 0 -4", &["41"; 16]), "");
        assert_eq!(parse_bdf(&text), Err("no glyph for byte 0x41".to_string()));
    }

    #[test]
    fn a_cell_of_another_size_is_refused() {
        let text = font().replace(&glyph_text(0x41, "8 16 0 -4", &["41"; 16]), &glyph_text(0x41, "6 12 0 -2", &["41"; 16]));
        assert!(parse_bdf(&text).unwrap_err().contains("8 by 16"));
        // Outside the range the size does not matter.
        let text = font().replace(&glyph_text(0x7F, "8 16 0 -4", &["7F"; 16]), &glyph_text(0x7F, "6 12 0 -2", &["7F"; 12]));
        assert!(parse_bdf(&text).is_ok());
    }

    #[test]
    fn a_glyph_with_the_wrong_number_of_rows_is_refused() {
        let text = font().replace(&glyph_text(0x41, "8 16 0 -4", &["41"; 16]), &glyph_text(0x41, "8 16 0 -4", &["41"; 15]));
        assert!(parse_bdf(&text).unwrap_err().contains("16 rows"));
    }

    #[test]
    fn a_row_that_is_not_one_byte_is_refused() {
        for bad in ["4", "414", "4G"] {
            let mut rows = ["41"; 16];
            rows[3] = bad;
            let text = font().replace(&glyph_text(0x41, "8 16 0 -4", &["41"; 16]), &glyph_text(0x41, "8 16 0 -4", &rows));
            assert!(parse_bdf(&text).unwrap_err().contains("two hexadecimal digits"), "{bad}");
        }
    }

    #[test]
    fn the_rendered_table_names_each_byte() {
        let text = render(&parse_bdf(&font()).unwrap());
        assert!(text.contains("pub const GLYPHS: [[u8; 16]; 95] = [\n"));
        assert!(text.contains(&format!("    [{}], // 0x41\n", ["0x41"; 16].join(", "))));
        assert!(text.contains("pub const fn glyph(byte: u8) -> &'static [u8; 16] {"));
    }

    /// The committed table is the one the font file gives (docs/10 section 5.3).
    #[test]
    fn the_committed_font_is_the_generated_one() {
        let committed = fs::read_to_string(generated()).unwrap();
        assert!(committed == expected().unwrap(), "lib/sk-kcore/src/font.rs differs: run `cargo xtask font`");
    }
}
